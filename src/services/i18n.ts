export type TranslationKey = keyof typeof translations['en'];

const LANGUAGE_STORAGE_KEY = '3plea_preferred_language_v1';

export function getStoredLanguage(): Language {
  try {
    if (typeof localStorage !== 'undefined') {
      const stored = localStorage.getItem(LANGUAGE_STORAGE_KEY);
      if (stored === 'en' || stored === 'ha') {
        return stored;
      }
    }
  } catch (e) {
    console.error('Failed to get stored language:', e);
  }
  return 'en';
}

export function saveStoredLanguage(lang: Language): void {
  try {
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem(LANGUAGE_STORAGE_KEY, lang);
    }
    if (typeof document !== 'undefined') {
      document.documentElement.lang = lang;
    }
  } catch (e) {
    console.error('Failed to save stored language:', e);
  }
}

export function t(key: TranslationKey, lang: Language): string {
  const map = translations[lang] || translations.en;
  return (map as any)[key] ?? translations.en[key] ?? (key as string);
}

