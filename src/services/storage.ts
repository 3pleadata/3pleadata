export function deduplicateTransactions(txs: Transaction[]): Transaction[] {
  if (!Array.isArray(txs)) return [];
  const seen = new Set<string>();
  const result: Transaction[] = [];
  for (const t of txs) {
    if (t && t.id) {
      if (!seen.has(t.id)) {
        seen.add(t.id);
        result.push(t);
      }
    }
  }
  return result;
}

